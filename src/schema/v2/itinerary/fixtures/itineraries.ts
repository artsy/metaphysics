/**
 * Static fixture data for City Guide itineraries.
 *
 * Gravity's itinerary support is built but not yet deployed, so the
 * `itinerary` root field and its resolvers read from here instead of a
 * loader. This is the ONLY place the fixture data lives — everything else
 * in `schema/v2/itinerary` reads through `fixtureItineraries` /
 * `fixtureItinerary`.
 *
 * When Gravity ships, the swap is:
 *   - delete this file
 *   - replace each `fixtureItinerary(...)` / `fixtureItineraries()` call
 *     site with the matching Gravity loader call (one line each)
 *
 * Keys are snake_case to match the shape Gravity's JSON will return, so
 * that swap doesn't require touching any resolver's field-mapping logic.
 *
 * The three curated itineraries below are ported from eigen's hand-built
 * mock data (`app/Scenes/CityGuide/Screens/Itinerary/utils/mockItineraries.ts`),
 * not invented here. Every `item_id` is a real slug taken from artsy.net —
 * eigen's mock file documents where each one comes from — and every
 * coordinate is the gallery's actual London location. Gravity has not
 * shipped real staging ids for these yet, so `item_id` stays a slug rather
 * than a BSON id: `ItineraryStop.item` resolves to null until real staging
 * ids are dropped in here — the batched entity resolution that turns
 * `item_type` / `item_id` into an actual node is part 2's job, and it can
 * only resolve entities that actually exist. Slugs are kept instead of
 * placeholder ids because they document what each stop actually points at.
 */

export interface FixtureItineraryStop {
  id: string
  position: number
  title: string | null
  title_override: string | null
  address: string | null
  address_override: string | null
  image_url: string | null
  latitude: number | null
  longitude: number | null
  start_at: string | null
  end_at: string | null
  note: string | null
  category: string | null
  is_free_admission: boolean | null
  item_type: string | null
  item_id: string | null
  event_type: string | null
  event_id: string | null
}

export interface FixtureItinerarySection {
  id: string
  title: string | null
  position: number
  stops_count: number
  stops: FixtureItineraryStop[]
}

export interface FixtureItineraryImage {
  image_url: string
  image_versions: string[]
  original_width: number
  original_height: number
}

export interface FixtureItinerary {
  id: string
  slug: string | null
  name: string
  subtitle: string | null
  description: string | null
  author_name: string | null
  // The owning user's id. Used only for connection-level "is this the
  // caller's own itinerary" filtering — never exposed on `ItineraryType`
  // itself (the association there is `authorName`, still under discussion
  // upstream).
  user_id: string | null
  city_slug: string
  is_curated: boolean
  share_token: string | null
  published_at: string | null
  // The itinerary's hero image, via Gravity's `HasArImage` concern —
  // `image_url` is a single templated URL string; `image_urls` is a hash of
  // versioned URLs; `image` is the nested ArImage object as `ArImage#as_json`
  // emits it (image_url, image_urls, image_versions, original_width,
  // original_height) that `ItineraryType#heroImage` resolves against with
  // `ImageType`. Curated guides have one; the personal fixture below
  // deliberately has none, to exercise the absent-value path.
  image_url: string | null
  image_urls: Record<string, string> | null
  image: FixtureItineraryImage | null
  sections_count: number
  sections: FixtureItinerarySection[]
}

